import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { chromium } from 'playwright-core';
const chromiumPath = process.env.AURALIS_TEST_BROWSER || (process.platform === 'linux' ? '/usr/bin/chromium' : '');
test('thumbnail control targets its own video and sends selected subtitle', {skip: !chromiumPath || !existsSync(chromiumPath)}, async () => {
  const browser = await chromium.launch({headless:true,executablePath:chromiumPath,args:['--no-sandbox']});
  try {
    const page = await browser.newPage();
    await page.route('https://www.youtube.com/**', route => route.fulfill({contentType:'text/html',body:'<a id="thumbnail" href="/watch?v=abcdef12345" style="position:relative;display:block;width:180px;height:95px;background:#555;overflow:hidden"></a>'}));
    await page.addInitScript(() => {
      const attach=Element.prototype.attachShadow;
      Element.prototype.attachShadow=function(init){return attach.call(this,{...init,mode:'open'})};
      globalThis.sentMessages=[];
      globalThis.chrome={runtime:{sendMessage:async message=>{globalThis.sentMessages.push(message);return {lookup:{state:'ready',token:'sample',title:'Sample',subtitles:[{code:'en',name:'English'}],choices:[{label:'1080p',size:104857600},{label:'128 kbps',audio:true,size:10485760,approx:true},{label:'720p'}]}}}}};
    });
    await page.goto('https://www.youtube.com/');
    await page.addScriptTag({content:readFileSync(new URL('../../auralis-extension/thumbnail.js',import.meta.url),'utf8')});
    const host=page.locator('#thumbnail > span'); await host.waitFor();
    const box=await host.boundingBox(); await page.mouse.click(box.x+10,box.y+10);
    const panel=page.locator('[data-auralis-thumbnail-menu]'); await page.waitForFunction(()=>document.querySelector('[data-auralis-thumbnail-menu]')?.shadowRoot?.querySelector('select[aria-label="Subtitles"]'));
    const panelBounds=await panel.evaluate(e=>{const p=e.shadowRoot.querySelector('.menu').getBoundingClientRect(),a=document.querySelector('#thumbnail').getBoundingClientRect();return {left:p.left,right:p.right,top:p.top,bottom:p.bottom,anchorBottom:a.bottom}});
    assert.ok(panelBounds.bottom>panelBounds.anchorBottom,'panel escapes the clipped thumbnail');assert.ok(panelBounds.left>=0&&panelBounds.right<=1280&&panelBounds.bottom<=720,'panel remains visible in viewport');
    assert.ok(await panel.evaluate(e=>[...e.shadowRoot.querySelectorAll('.subtitle-list button')].some(b=>b.textContent.includes('English'))));
    const sections=await panel.evaluate(e=>[...e.shadowRoot.querySelectorAll('.menu section')].map(section=>section.textContent));
    assert.ok(sections.some(text=>text.includes('Video')&&text.includes('1080p')));
    assert.ok(sections.some(text=>text.includes('Audio')&&text.includes('128 kbps')));
    assert.ok(sections.some(text=>text.includes('Subtitles')&&text.includes('English')));
    assert.ok(sections.some(text=>text.includes('100 MB')&&text.includes('Size unavailable')));
    assert.ok(sections.some(text=>text.includes('~10 MB')));
    assert.ok(sections.some(text=>text.includes('English')&&text.includes('Size unavailable')));
    const anchorBefore=await host.boundingBox(), header=await panel.locator('.dragbar').boundingBox(), before=await panel.locator('.menu').boundingBox();
    assert.ok(before.width<=320&&before.height<=330,'quality panel is compact');
    await page.mouse.move(header.x+40,header.y+10);await page.mouse.down();await page.mouse.move(header.x+120,header.y+50,{steps:4});await page.mouse.up();
    const after=await panel.locator('.menu').boundingBox(), anchorAfter=await host.boundingBox();
    assert.equal(after.x,before.x);assert.equal(after.y,before.y);assert.equal(anchorAfter.x,anchorBefore.x);assert.equal(anchorAfter.y,anchorBefore.y);
    assert.equal(await panel.locator('[role="tab"][aria-selected="true"]').innerText(),'Video');
    await panel.locator('[role="tab"]', {hasText:'Audio'}).click();
    assert.equal(await panel.locator('[role="tab"][aria-selected="true"]').innerText(),'Audio');
    await panel.locator('[role="tab"]', {hasText:'Subtitles'}).click();
    await panel.locator('.subtitle-list button', {hasText:'English'}).click();
    assert.equal(await panel.evaluate(e=>e.shadowRoot.querySelector('select[aria-label="Subtitles"]').value),'manual:en');
    await panel.locator('[role="tab"]', {hasText:'Video'}).click();
    // Reopening and reinjecting must never leave an interactive old menu behind.
    await page.keyboard.press('Escape');
    assert.equal(await panel.count(),0);
    await host.locator('button.control').click();
    assert.equal(await panel.count(),1);
    await page.addScriptTag({content:readFileSync(new URL('../../auralis-extension/thumbnail.js',import.meta.url),'utf8')});
    assert.equal(await panel.count(),0);
    assert.equal(await page.locator('[data-auralis-thumbnail-control]').count(),1);
    await host.locator('button.control').click();
    assert.equal(await panel.count(),1);
    await page.waitForFunction(()=>document.querySelector('[data-auralis-thumbnail-menu]')?.shadowRoot?.querySelector('select[aria-label="Subtitles"]'));
    await panel.evaluate(e=>{const root=e.shadowRoot;root.querySelector('select[aria-label="Subtitles"]').value='manual:en';[...root.querySelectorAll('.menu button')].find(b=>b.textContent.includes('1080p')).click()});
    const sent=await page.evaluate(()=>globalThis.sentMessages);
    assert.equal(sent.some(m=>m.type==='youtube-sign-in'),false);
    assert.equal(await panel.locator('.sign-in').count(),0);
    assert.equal(sent[0].url,'https://www.youtube.com/watch?v=abcdef12345');
    assert.deepEqual(sent.find(m=>m.type==='video-pick').subs.langs,['en']);
    await panel.getByRole('combobox',{name:'Cookies'}).click();
    await panel.getByRole('option',{name:'Choose cookies file'}).click();
    assert.equal(await panel.getByLabel('Cookies file').isVisible(),true);
    await panel.locator('input[type="file"]').setInputFiles({name:'cookies.txt',mimeType:'text/plain',buffer:Buffer.from('# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t0\tSID\ttest-value\n')});
    assert.equal(await panel.evaluate(e=>e.shadowRoot.querySelector('input[type="file"]').files.length),1);
    await panel.evaluate(e=>e.shadowRoot.querySelector('.fetch').click());
    await page.waitForFunction(()=>globalThis.sentMessages.some(m=>m.cookieMode==='file'));
    const uploaded=await page.evaluate(()=>globalThis.sentMessages.find(m=>m.cookieMode==='file'));
    assert.match(uploaded.cookieFile,/youtube\.com/);
    await page.setViewportSize({width:320,height:240});
    await page.locator('#thumbnail').evaluate(e=>{e.style.position='absolute';e.style.left='130px';e.style.top='140px'});
    await page.evaluate(()=>window.dispatchEvent(new Event('resize')));
    await page.waitForTimeout(100);
    const narrow=await panel.evaluate(e=>{const m=e.shadowRoot.querySelector('.menu'),r=m.getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,scrollHeight:m.scrollHeight,clientHeight:m.clientHeight}});
    assert.ok(narrow.left>=0&&narrow.top>=0&&narrow.right<=320&&narrow.bottom<=240,'menu fits a small viewport');
    assert.ok(narrow.scrollHeight>narrow.clientHeight,'overflowing options stay scrollable');
    await page.locator('#thumbnail').evaluate(e=>e.setAttribute('href','/watch?v=zyxwvu98765'));
    await page.waitForTimeout(100);
    assert.equal(await host.count(),1);
  } finally { await browser.close(); }
});
